-- 6. cancel_booking procedure
CREATE OR REPLACE PROCEDURE scenario6_events.cancel_booking(p_booking_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_event_id integer;
    v_seats    integer;
BEGIN
    SELECT event_id, seats
    INTO v_event_id, v_seats
    FROM scenario6_events.bookings
    WHERE booking_id = p_booking_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active booking with ID %', p_booking_id;
        RETURN;
    END IF;

    UPDATE scenario6_events.bookings
    SET status = 'CANCELLED' WHERE booking_id = p_booking_id;

    UPDATE scenario6_events.events
    SET available_seats = available_seats + v_seats
    WHERE event_id = v_event_id;

    RAISE NOTICE 'Booking % cancelled; % seats released', p_booking_id, v_seats;
END;
$$;

CALL scenario6_events.cancel_booking(1);
CALL scenario6_events.cancel_booking(1);  -- second call: must not release again

SELECT * FROM scenario6_events.events ORDER BY event_id;
SELECT booking_id, status FROM scenario6_events.bookings ORDER BY booking_id;

-- 7. Explicit cursor - full or nearly full events
CREATE OR REPLACE PROCEDURE scenario6_events.show_full_events()
LANGUAGE plpgsql
AS $$
DECLARE
    v_event record;
    c_full CURSOR FOR
        SELECT event_name, available_seats
        FROM scenario6_events.events
        WHERE available_seats <= 2
        ORDER BY event_id;
BEGIN
    OPEN c_full;
    LOOP
        FETCH c_full INTO v_event;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Nearly full: % (% seats remaining)', v_event.event_name, v_event.available_seats;
    END LOOP;
    CLOSE c_full;
END;
$$;

CALL scenario6_events.show_full_events();

