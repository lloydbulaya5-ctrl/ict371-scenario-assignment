-- 2. IF ELSIF ELSE - event capacity status
DO $$
DECLARE
    v_seats integer;
BEGIN
    SELECT available_seats INTO v_seats
    FROM events WHERE event_id = 2;

    IF v_seats = 0 THEN
        RAISE NOTICE 'Event full';
    ELSIF v_seats <= 2 THEN
        RAISE NOTICE 'Event nearly full: % seats left', v_seats;
    ELSE
        RAISE NOTICE 'Event has plenty of seats: % left', v_seats;
    END IF;
END $$;

-- 3. WHILE (booking reminder days) + FOR (entrance checks)
DO $$
DECLARE
    v_day integer := 1;
BEGIN
    WHILE v_day <= 3 LOOP
        RAISE NOTICE 'Booking reminder day %', v_day;
        v_day := v_day + 1;
    END LOOP;

    FOR v_check IN 1..3 LOOP
        RAISE NOTICE 'Entrance check %', v_check;
    END LOOP;
END $$;

-- 4. book_seats procedure
CREATE OR REPLACE PROCEDURE scenario6_events.book_seats(
    p_event_id integer,
    p_student_number text,
    p_seats integer
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_available  integer;
    v_booking_id integer;
BEGIN
    IF p_seats <= 0 THEN
        RAISE EXCEPTION 'Seats requested must be positive'
        USING ERRCODE = '22023';
    END IF;

    SELECT available_seats INTO v_available
    FROM scenario6_events.events
    WHERE event_id = p_event_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'Event % does not exist', p_event_id;
        RETURN;
    ELSIF v_available < p_seats THEN
        RAISE NOTICE 'Insufficient seats: only % available', v_available;
        RETURN;
    END IF;

    UPDATE scenario6_events.events
    SET available_seats = available_seats - p_seats
    WHERE event_id = p_event_id;

    INSERT INTO scenario6_events.bookings (event_id, student_number, seats, status)
    VALUES (p_event_id, p_student_number, p_seats, 'ACTIVE')
    RETURNING booking_id INTO v_booking_id;

    RAISE NOTICE 'Booking % created for student %', v_booking_id, p_student_number;
END;
$$;

