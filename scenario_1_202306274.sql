-- 6. return_book procedure
CREATE OR REPLACE PROCEDURE scenario1_lib.return_book(p_loan_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_book_id  integer;
    v_quantity integer;
BEGIN
    SELECT book_id, quantity
    INTO v_book_id, v_quantity
    FROM scenario1_lib.book_loans
    WHERE loan_id = p_loan_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active loan with ID %', p_loan_id;
        RETURN;
    END IF;

    UPDATE scenario1_lib.book_loans
    SET status = 'RETURNED' WHERE loan_id = p_loan_id;

    UPDATE scenario1_lib.books
    SET available_copies = available_copies + v_quantity
    WHERE book_id = v_book_id;

    RAISE NOTICE 'Loan % returned; % copies restored', p_loan_id, v_quantity;
END;
$$;

