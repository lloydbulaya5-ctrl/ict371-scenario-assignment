-- 7. Explicit cursor - books with few copies
CREATE OR REPLACE PROCEDURE scenario1_lib.show_low_stock_books()
LANGUAGE plpgsql
AS $$
DECLARE
    v_book record;
    c_low CURSOR FOR
        SELECT title, available_copies
        FROM scenario1_lib.books
        WHERE available_copies <= 2
        ORDER BY book_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_book;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low stock: % (% remaining)', v_book.title, v_book.available_copies;
    END LOOP;
    CLOSE c_low;
END;
$$;

CALL scenario1_lib.show_low_stock_books();

