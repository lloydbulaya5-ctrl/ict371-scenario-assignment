-- 7. Explicit cursor - sessions with few workstations remaining
CREATE OR REPLACE PROCEDURE scenario2_lab.show_low_capacity_sessions()
LANGUAGE plpgsql
AS $$
DECLARE
    v_session record;
    c_low CURSOR FOR
        SELECT session_name, available_workstations
        FROM scenario2_lab.lab_sessions
        WHERE available_workstations <= 2
        ORDER BY session_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_session;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low capacity: % (% remaining)', v_session.session_name, v_session.available_workstations;
    END LOOP;
    CLOSE c_low;
END;
$$;

CALL scenario2_lab.show_low_capacity_sessions();

