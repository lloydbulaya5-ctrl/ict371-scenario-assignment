-- 6. reverse_dispensing procedure
CREATE OR REPLACE PROCEDURE scenario4_clinic.reverse_dispensing(p_record_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_medicine_id integer;
    v_quantity    integer;
BEGIN
    SELECT medicine_id, quantity
    INTO v_medicine_id, v_quantity
    FROM scenario4_clinic.dispensing_records
    WHERE record_id = p_record_id AND status = 'DISPENSED'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No dispensed record with ID %', p_record_id;
        RETURN;
    END IF;

    UPDATE scenario4_clinic.dispensing_records
    SET status = 'REVERSED' WHERE record_id = p_record_id;

    UPDATE scenario4_clinic.medicines
    SET stock_quantity = stock_quantity + v_quantity
    WHERE medicine_id = v_medicine_id;

    RAISE NOTICE 'Record % reversed; % units restored', p_record_id, v_quantity;
END;
$$;

CALL scenario4_clinic.reverse_dispensing(1);
CALL scenario4_clinic.reverse_dispensing(1);  -- second call: must not restore again

SELECT * FROM scenario4_clinic.medicines ORDER BY medicine_id;
SELECT record_id, status FROM scenario4_clinic.dispensing_records ORDER BY record_id;

-- 7. Explicit cursor - medicines below low-stock threshold
CREATE OR REPLACE PROCEDURE scenario4_clinic.show_low_stock_medicines()
LANGUAGE plpgsql
AS $$
DECLARE
    v_med record;
    c_low CURSOR FOR
        SELECT medicine_name, stock_quantity
        FROM scenario4_clinic.medicines
        WHERE stock_quantity <= 2
        ORDER BY medicine_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_med;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low stock: % (% remaining)', v_med.medicine_name, v_med.stock_quantity;
    END LOOP;
    CLOSE c_low;
END;
$$;

CALL scenario4_clinic.show_low_stock_medicines();

