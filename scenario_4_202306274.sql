-- 2. IF ELSIF ELSE - stock status
DO $$
DECLARE
    v_stock integer;
BEGIN
    SELECT stock_quantity INTO v_stock
    FROM medicines WHERE medicine_id = 2;

    IF v_stock = 0 THEN
        RAISE NOTICE 'Medicine out of stock';
    ELSIF v_stock <= 2 THEN
        RAISE NOTICE 'Medicine low on stock: % remaining', v_stock;
    ELSE
        RAISE NOTICE 'Medicine sufficiently stocked: % remaining', v_stock;
    END IF;
END $$;

-- 3. WHILE (stock review days) + FOR (shelf inspections)
DO $$
DECLARE
    v_day integer := 1;
BEGIN
    WHILE v_day <= 3 LOOP
        RAISE NOTICE 'Stock review day %', v_day;
        v_day := v_day + 1;
    END LOOP;

    FOR v_shelf IN 1..3 LOOP
        RAISE NOTICE 'Shelf inspection %', v_shelf;
    END LOOP;
END $$;

-- 4. dispense_medicine procedure
CREATE OR REPLACE PROCEDURE scenario4_clinic.dispense_medicine(
    p_medicine_id integer,
    p_student_number text,
    p_quantity integer
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_stock    integer;
    v_record_id integer;
BEGIN
    IF p_quantity <= 0 THEN
        RAISE EXCEPTION 'Dispensing quantity must be positive'
        USING ERRCODE = '22023';
    END IF;

    SELECT stock_quantity INTO v_stock
    FROM scenario4_clinic.medicines
    WHERE medicine_id = p_medicine_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'Medicine % does not exist', p_medicine_id;
        RETURN;
    ELSIF v_stock < p_quantity THEN
        RAISE NOTICE 'Insufficient stock: only % available', v_stock;
        RETURN;
    END IF;

    UPDATE scenario4_clinic.medicines
    SET stock_quantity = stock_quantity - p_quantity
    WHERE medicine_id = p_medicine_id;

    INSERT INTO scenario4_clinic.dispensing_records (medicine_id, student_number, quantity, status)
    VALUES (p_medicine_id, p_student_number, p_quantity, 'DISPENSED')
    RETURNING record_id INTO v_record_id;

    RAISE NOTICE 'Dispensing record % created for student %', v_record_id, p_student_number;
END;
$$;

